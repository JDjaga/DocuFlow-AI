/**
 * AiResults - sections A-F of an analysis, plus the result actions.
 *
 *   A. Document summary        D. Priority + explanation
 *   B. Key entities             E. Suggested action items
 *   C. Document category        F. Additional observations
 *
 * Everything shown here comes from the JSON validated by Pydantic on the
 * backend (backend/app/schemas/ai.py).
 */
import { AlertCircle, CalendarClock, Eye, FilePenLine, ListPlus, RefreshCw, Trash2 } from 'lucide-react';
import Badge from '../common/Badge';
import { PRIORITY_STYLES } from '../../utils/constants';
import { formatDate } from '../../utils/formatters';

function Section({ icon: Icon, title, children, hint }) {
  return (
    <section className="rounded-xl border border-slate-200 bg-white p-5">
      <div className="mb-3 flex items-center gap-2">
        <span className="flex h-7 w-7 items-center justify-center rounded-lg bg-slate-100 text-slate-500">
          <Icon className="h-4 w-4" />
        </span>
        <h3 className="text-sm font-semibold text-slate-900">{title}</h3>
        {hint && <span className="ml-auto text-xs text-slate-400">{hint}</span>}
      </div>
      {children}
    </section>
  );
}

const ENTITY_ICONS = { Organization: '🏢', Person: '👤', Date: '📅', Location: '📍', Money: '💰' };

// Honest labels per provider - never claim Gemini when another one answered.
const PROVIDER_LABELS = {
  mock: 'Mock AI',
  gemini: 'Google Gemini',
  openrouter: 'OpenRouter',
  ollama: 'Ollama (local)',
};

export default function AiResults({ document, aiProvider, aiNotice, actions }) {
  const isMock = aiProvider === 'mock';
  const isGeneral = document.document_type === 'general';
  const providerLabel = PROVIDER_LABELS[aiProvider] || aiProvider || 'AI provider';

  return (
    <div className="space-y-4">
      {/* Fallback notice - only present when a provider really failed over. */}
      {aiNotice && (
        <div className="flex items-start gap-2.5 rounded-xl border border-amber-300 bg-amber-50 px-4 py-3 text-xs leading-relaxed text-amber-800">
          <span className="text-sm">⚠️</span>
          <p>
            <span className="font-semibold">Automatic fallback:</span> {aiNotice}
          </p>
        </div>
      )}

      {/* Provider banner - never pretend mock output is Gemini. */}
      <div
        className={`flex items-start gap-2.5 rounded-xl border px-4 py-3 text-xs leading-relaxed ${
          isMock
            ? 'border-amber-200 bg-amber-50 text-amber-800'
            : 'border-emerald-200 bg-emerald-50 text-emerald-800'
        }`}
      >
        <span className="text-sm">{isMock ? '🧪' : '✨'}</span>
        <p>
          <span className="font-semibold">
            {isMock ? 'Mock AI mode' : `${providerLabel} mode`}:
          </span>{' '}
          {isMock
            ? 'this analysis was produced locally by the deterministic mock engine - no external AI was called. It is clearly labelled so it is never mistaken for real AI output.'
            : `this analysis was generated by ${providerLabel} and validated with Pydantic before being stored.`}
        </p>
      </div>

      {/* A. Summary */}
      <Section icon={Eye} title="Document Summary" hint="AI generated">
        <p className="text-sm leading-relaxed text-slate-700">{document.summary}</p>
      </Section>

      <div className="grid gap-4 lg:grid-cols-2">
        {/* B. Key entities */}
        <Section icon={CalendarClock} title="Key Entities" hint={`${document.key_entities.length} found`}>
          {document.key_entities.length === 0 ? (
            <p className="text-sm text-slate-500">
              No explicit entities (names, dates, amounts) were detected in this document.
            </p>
          ) : (
            <ul className="max-h-56 space-y-2 overflow-y-auto pr-1">
              {document.key_entities.map((entity, index) => (
                <li
                  key={`${entity.type}-${entity.value}-${index}`}
                  className="flex items-start justify-between gap-3 rounded-lg bg-slate-50 px-3 py-2"
                >
                  <span className="flex items-center gap-2 text-xs font-semibold text-slate-500">
                    <span aria-hidden="true">{ENTITY_ICONS[entity.type] || '🔎'}</span>
                    {entity.type}
                  </span>
                  <span className="break-all text-right text-sm text-slate-800">{entity.value}</span>
                </li>
              ))}
            </ul>
          )}
        </Section>

        {/* C + D. Category and priority */}
        <div className="space-y-4">
          <Section icon={FilePenLine} title="Document Category">
            <div className="flex items-center justify-between gap-3">
              <span className="rounded-lg bg-indigo-50 px-3 py-1.5 text-sm font-semibold text-indigo-700">
                {document.category}
              </span>
              <span className="text-xs text-slate-400">from 7 supported categories</span>
            </div>
          </Section>

          <Section icon={AlertCircle} title="Priority Level">
            <div className="flex items-center gap-2">
              <Badge label={document.priority} className={PRIORITY_STYLES[document.priority]} />
            </div>
            <p className="mt-2 text-sm leading-relaxed text-slate-600">{document.priority_reason}</p>
          </Section>
        </div>
      </div>

      {/* E. Action items */}
      <Section
        icon={ListPlus}
        title="Suggested Action Items"
        hint={isGeneral ? 'disabled for general documents' : `${document.action_items.length} suggested`}
      >
        {isGeneral ? (
          <p className="text-sm text-slate-500">
            This is a <span className="font-medium text-slate-700">general document</span> - the AI still
            summarizes and extracts entities, but workflow action items and task creation are turned off.
            Use the chat panel to ask questions about it.
          </p>
        ) : document.action_items.length === 0 ? (
          <p className="text-sm text-slate-500">No action items were suggested for this document.</p>
        ) : (
          <ol className="space-y-2.5">
            {document.action_items.map((item, index) => (
              <li key={`${item.title}-${index}`} className="rounded-lg border border-slate-200 bg-slate-50/70 px-4 py-3">
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <p className="text-sm font-medium text-slate-900">
                    <span className="mr-2 text-slate-400">{index + 1}.</span>
                    {item.title}
                  </p>
                  <Badge label={item.priority} className={PRIORITY_STYLES[item.priority] || 'border-slate-200 bg-slate-100 text-slate-600'} />
                </div>
                {item.description && <p className="mt-1 text-xs leading-relaxed text-slate-600">{item.description}</p>}
                <p className="mt-1.5 text-xs text-slate-400">
                  {item.due_date ? `Suggested due date: ${formatDate(item.due_date)}` : 'No due date identified in the document'}
                </p>
              </li>
            ))}
          </ol>
        )}
      </Section>

      {/* F. Observations */}
      <Section icon={AlertCircle} title="Additional Observations" hint={`${document.observations.length} notes`}>
        {document.observations.length === 0 ? (
          <p className="text-sm text-slate-500">Nothing extra to report.</p>
        ) : (
          <ul className="space-y-2">
            {document.observations.map((observation, index) => (
              <li key={index} className="flex gap-2 text-sm text-slate-600">
                <span className="mt-1.5 h-1.5 w-1.5 shrink-0 rounded-full bg-indigo-400" />
                {observation}
              </li>
            ))}
          </ul>
        )}
      </Section>

      {/* Result actions */}
      {actions && (
        <div className="flex flex-wrap gap-2.5 rounded-xl border border-slate-200 bg-slate-50 p-4">
          <button type="button" className="btn-secondary" onClick={actions.onView}>
            <Eye className="h-4 w-4" /> View Full Analysis
          </button>
          <button type="button" className="btn-secondary" onClick={actions.onEdit}>
            <FilePenLine className="h-4 w-4" /> Edit Document Details
          </button>
          {!isGeneral && (
            <button type="button" className="btn-primary" onClick={actions.onCreateTasks} disabled={!document.action_items.length}>
              <ListPlus className="h-4 w-4" /> Create Tasks
            </button>
          )}
          <button type="button" className="btn-secondary" onClick={actions.onReanalyze} disabled={actions.busy}>
            <RefreshCw className="h-4 w-4" /> Reanalyze
          </button>
          <button type="button" className="btn-danger" onClick={actions.onDelete}>
            <Trash2 className="h-4 w-4" /> Delete
          </button>
        </div>
      )}
    </div>
  );
}
